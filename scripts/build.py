"""Build independent theme entry points and illustrated previews; stdlib only."""
import argparse
from html import escape
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def prompt_line(y, segments):
    x = 36
    elements = []
    for color, text in segments:
        width = len(text) * 10.2
        displayed = escape(text.replace(" ", "\u00a0"))
        elements.append(f'<text x="{x:.1f}" y="{y}" fill="{color}" textLength="{width:.1f}" lengthAdjust="spacingAndGlyphs">{displayed}</text>')
        x += width
    return "".join(elements)


def outputs():
    files = {}
    for mode, p in json.loads((ROOT / "palette.json").read_text())["variants"].items():
        colors = " ".join(f"{role} '{p[role]}'" for role in ("accent", "directory", "git", "error", "muted"))
        files[f"bacumi-{mode}.zsh-theme"] = f'''# Bacumi {mode.title()} · MIT License · Copyright (c) 2026 Bacumi
# Generated by scripts/build.py from palette revision bacumi-terminal-1.
typeset -gA _bacumi_palette
_bacumi_palette=({colors})
source "${{${{(%):-%x}}:A:h}}/lib/prompt.zsh"
'''
        files[f"bacumi-developer-{mode}.zsh-theme"] = f'''# Bacumi Developer {mode.title()} · MIT License · Copyright (c) 2026 Bacumi
# Generated by scripts/build.py from palette revision bacumi-terminal-1.
typeset -gA _bacumi_palette
_bacumi_palette=({colors})
source "${{${{(%):-%x}}:A:h}}/lib/developer-prompt.zsh"
'''
        rows = [f'<text x="36" y="44" font-size="21" fill="{p["foreground"]}">Bacumi {mode.title()} · Oh My Zsh</text>',
                prompt_line(110, [(p["directory"], "~/work/bacumi"), (p["git"], " git:main"), (p["accent"], " > "), (p["foreground"], "git status")]),
                f'<text x="36" y="148" fill="{p["muted"]}">On branch main · working tree clean</text>',
                prompt_line(214, [(p["directory"], "~/work/bacumi"), (p["git"], " git:feature*"), (p["accent"], " > "), (p["foreground"], "false")]),
                prompt_line(252, [(p["directory"], "~/work/bacumi"), (p["git"], " git:feature*"), (p["error"], " !1"), (p["accent"], " > ")]),
                f'<text x="36" y="332" fill="{p["muted"]}" font-size="12">Illustrated prompt preview · not a native screenshot</text>']
        files[f"assets/bacumi-{mode}.svg"] = f'<svg xmlns="http://www.w3.org/2000/svg" width="800" height="370" viewBox="0 0 800 370" role="img" aria-label="Bacumi {mode} illustrated Zsh prompt"><rect width="800" height="370" rx="16" fill="{p["background"]}"/><g font-family="ui-monospace, Menlo, monospace" font-size="17">' + "".join(rows) + '</g></svg>\n'
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Rebuild required: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print("Bacumi Dark/Light entry points and illustrated previews verified." if args.check else "Built Bacumi Dark/Light.")
